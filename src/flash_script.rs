//! Export of a flash plan as a script: `*.cmd` on Windows, `*.sh` elsewhere.
//!
//! The script is a plain transcription of the procedures that are about to be
//! flashed (and the standalone erases), so the same flash can be repeated,
//! checked by hand, or run on a machine without the app. Only the tool's own
//! command line is used — which is why the built-in fastboot, that has none,
//! is written out as `fastboot` from the Android platform-tools.
//!
//! An external tool can also be copied next to the script ([`copy_tool`]) and
//! started from there, so the script runs on a machine that has no `fastboot`
//! installed at all.
//!
//! Comments are English, like every other generated file: they are part of
//! the script, not of the interface.

use std::path::Path;

use crate::flash_engine::{Engine, Mfastboot};
use crate::flashfile::{FlashOp, FlashPackage};

/// The files a Windows `fastboot` loads from its own folder. They are copied
/// next to the script together with the tool, or it would not start there.
const WINDOWS_HELPERS: &[&str] = &["AdbWinApi.dll", "AdbWinUsbApi.dll"];

/// The shell a script is written for; the host decides which one.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shell {
    /// Windows `cmd.exe`.
    Cmd,
    /// POSIX `sh`.
    Sh,
}

impl Shell {
    /// The shell of the machine the app runs on.
    pub fn for_host() -> Self {
        if cfg!(windows) {
            Self::Cmd
        } else {
            Self::Sh
        }
    }

    /// Extension of the script, without the dot.
    pub fn extension(self) -> &'static str {
        match self {
            Self::Cmd => "cmd",
            Self::Sh => "sh",
        }
    }

    /// Name offered in the save dialog, e.g. `XT2451-2_flash.cmd`.
    pub fn file_name(self, model: Option<&str>) -> String {
        match model.map(sanitize).filter(|model| !model.is_empty()) {
            Some(model) => format!("{model}_flash.{}", self.extension()),
            None => format!("flash.{}", self.extension()),
        }
    }

    /// The marker that starts a comment line.
    fn comment(self) -> &'static str {
        match self {
            Self::Cmd => "REM",
            Self::Sh => "#",
        }
    }

    /// Quotes one value for this shell.
    fn quote(self, value: &str) -> String {
        match self {
            // `%` starts a variable in a batch file, so it has to be doubled.
            Self::Cmd => format!("\"{}\"", value.replace('%', "%%")),
            // Inside double quotes only these three keep their meaning.
            Self::Sh => {
                let escaped = value
                    .replace('\\', "\\\\")
                    .replace('"', "\\\"")
                    .replace('$', "\\$")
                    .replace('`', "\\`");

                format!("\"{escaped}\"")
            }
        }
    }
}

/// Everything the script is written from.
pub struct ScriptJob<'a> {
    pub package: &'a FlashPackage,
    /// The procedures that will run (the checked ones, in package order).
    pub steps: &'a [FlashOp],
    /// Erases the "Erase …" buttons added on top of the package.
    pub extra_erases: &'a [String],
    /// The tool the app would flash with, so the script starts the same one.
    /// A built-in flash has no command line, so it becomes `fastboot`.
    pub engine: &'a Engine,
    /// The file name the tool was copied to next to the script, when the user
    /// asked for that: the script then starts that copy instead of the
    /// installed tool. `None` addresses the tool where it is installed.
    pub copied_tool: Option<&'a str>,
    /// Device the script addresses; empty writes it without `-s`.
    pub serial: &'a str,
    pub shell: Shell,
}

/// Renders the script.
pub fn render(job: &ScriptJob<'_>) -> String {
    let shell = job.shell;
    let comment = shell.comment();
    let mut out = String::new();

    if shell == Shell::Sh {
        out.push_str("#!/bin/sh\n");
    } else {
        out.push_str("@echo off\n");
    }

    // What the script does and where its images are.
    let firmware = match (&job.package.model, &job.package.software_version) {
        (Some(model), Some(version)) => format!("{model} ({version})"),
        (Some(model), None) => model.clone(),
        (None, Some(version)) => version.clone(),
        (None, None) => "the firmware package".to_owned(),
    };

    out.push_str(&format!(
        "{comment} Flash script for {firmware}, generated by LMN Flash.\n"
    ));
    out.push_str(&format!(
        "{comment} {selected} of the {total} procedures of the package are written below{erases}.\n",
        selected = job.steps.len(),
        total = job.package.steps.len(),
        erases = match job.extra_erases.len() {
            0 => String::new(),
            1 => ", followed by one extra erase".to_owned(),
            count => format!(", followed by {count} extra erases"),
        },
    ));
    out.push_str(&format!(
        "{comment} The images are read from the folder below; change the line if they\n\
         {comment} are somewhere else (a package opened from a ZIP is unpacked into a\n\
         {comment} temporary folder, which may be gone by now).\n",
    ));

    match shell {
        Shell::Cmd => out.push_str(&format!(
            "cd /d {}\n",
            shell.quote(&job.package.directory.display().to_string())
        )),
        Shell::Sh => out.push_str(&format!(
            "cd {}\n",
            shell.quote(&job.package.directory.display().to_string())
        )),
    }

    // The tool, and the device when one was selected.
    out.push('\n');
    out.push_str(&format!(
        "{comment} Tool and device: edit these lines, not the commands below.\n"
    ));

    let (tool_line, tool_note) = tool_assignment(shell, job.engine, job.copied_tool);
    out.push_str(&tool_line);
    out.push('\n');

    if let Some(note) = tool_note {
        for line in note.lines() {
            out.push_str(&format!("{comment} {line}\n"));
        }
    }

    let mut device = String::new();
    if !job.serial.is_empty() {
        match shell {
            Shell::Cmd => out.push_str(&format!("set \"SERIAL={}\"\n", job.serial)),
            Shell::Sh => out.push_str(&format!("SERIAL={}\n", shell.quote(job.serial))),
        }

        device = match shell {
            Shell::Cmd => " -s \"%SERIAL%\"".to_owned(),
            Shell::Sh => " -s \"$SERIAL\"".to_owned(),
        };
    } else {
        out.push_str(&format!(
            "{comment} No device was selected, so the tool is left to pick the only one.\n"
        ));
    }

    let prefix = match shell {
        Shell::Cmd => format!("\"%FASTBOOT%\"{device}"),
        Shell::Sh => format!("\"$FASTBOOT\"{device}"),
    };

    // The procedures, in the order they run.
    out.push('\n');
    for step in job.steps {
        out.push_str(&format!("{prefix} {}\n", step_command(shell, step)));
    }

    // The standalone erases, last — like the app runs them.
    if !job.extra_erases.is_empty() {
        out.push('\n');
        out.push_str(&format!(
            "{comment} Extra erases, added in the dialog. A partition the device does not\n\
             {comment} have makes the tool print an error, which is not fatal.\n"
        ));

        for partition in job.extra_erases {
            out.push_str(&format!("{prefix} erase {partition}\n"));
        }
    }

    out
}

/// The line that points `FASTBOOT` at the tool, plus a note for the header
/// when it is not simply the selected build.
///
/// Complete lines are built here rather than a bare value: the copy next to
/// the script is addressed with a shell expression (`%~dp0`, `$(dirname …)`),
/// which must not be escaped like a file path.
fn tool_assignment(
    shell: Shell,
    engine: &Engine,
    copied_tool: Option<&str>,
) -> (String, Option<&'static str>) {
    if let (Engine::Mfastboot(_), Some(name)) = (engine, copied_tool) {
        let line = match shell {
            // `%~dp0` is the folder the script itself sits in, whatever the
            // working directory is.
            Shell::Cmd => format!("set \"FASTBOOT=%~dp0{name}\""),
            // The script changes into the package folder first, so the folder
            // of the script is resolved while this line runs.
            Shell::Sh => {
                format!("FASTBOOT=\"$(cd \"$(dirname \"$0\")\" && pwd)/{name}\"")
            }
        };

        return (
            line,
            Some(
                "The tool is copied into the folder of this script, and the line above\n\
                 starts that copy; the files written next to the script belong to it.",
            ),
        );
    }

    let (tool, note) = tool_of(engine);
    let line = match shell {
        Shell::Cmd => format!("set \"FASTBOOT={tool}\""),
        Shell::Sh => format!("FASTBOOT={}", shell.quote(&tool)),
    };

    (line, note)
}

/// The command that starts the steps, plus a note for the header when it is
/// not simply the selected build.
fn tool_of(engine: &Engine) -> (String, Option<&'static str>) {
    match engine {
        Engine::Mfastboot(tool) => (tool.path.display().to_string(), None),
        // The built-in engine is part of the app, so a script can only use the
        // `fastboot` of the Android platform-tools.
        Engine::Builtin => (
            "fastboot".to_owned(),
            Some(
                "The built-in fastboot has no command line, so this script runs `fastboot`\n\
                 from the Android platform-tools: put it on PATH or edit the line above.",
            ),
        ),
    }
}

/// Copies the tool the script starts into `directory` and returns the file
/// name it was written as, so the script can address it there.
///
/// A Windows build loads two DLLs from its own folder, so those are copied
/// with it — a helper that is not there (every other platform) is skipped
/// rather than reported. A file that is already the one being copied (the
/// script is written into the tool's own folder) is left alone: copying it
/// onto itself would empty it.
pub(crate) fn copy_tool(tool: &Mfastboot, directory: &Path) -> Result<String, String> {
    copy_tool_into(tool, directory, cfg!(windows))
}

/// [`copy_tool`] with the platform stated, so a test can check the Windows
/// behaviour everywhere.
fn copy_tool_into(
    tool: &Mfastboot,
    directory: &Path,
    windows: bool,
) -> Result<String, String> {
    let name = tool
        .path
        .file_name()
        .map(|name| sanitize(&name.to_string_lossy()))
        .filter(|name| !name.is_empty())
        .ok_or_else(|| format!("{} has no file name", tool.path.display()))?;

    write_copy(&tool.path, &directory.join(&name))?;

    if windows {
        if let Some(folder) = tool.path.parent() {
            for helper in WINDOWS_HELPERS {
                let source = folder.join(helper);

                if source.is_file() {
                    write_copy(&source, &directory.join(helper))?;
                }
            }
        }
    }

    Ok(name)
}

/// Copies one file, unless the destination already is the source.
fn write_copy(source: &Path, destination: &Path) -> Result<(), String> {
    if source == destination
        || matches!(
            (source.canonicalize(), destination.canonicalize()),
            (Ok(source), Ok(destination)) if source == destination
        )
    {
        return Ok(());
    }

    std::fs::copy(source, destination)
        .map_err(|error| format!("{}: {error}", destination.display()))?;

    Ok(())
}

/// One procedure as the tool's arguments (`flash boot "boot.img"`).
fn step_command(shell: Shell, step: &FlashOp) -> String {
    match step {
        FlashOp::Flash {
            partition, file, ..
        } => format!("flash {partition} {}", shell.quote(file)),
        FlashOp::Erase { partition } => format!("erase {partition}"),
        FlashOp::Oem { var } => format!("oem {var}"),
        FlashOp::Getvar { var } => format!("getvar {var}"),
    }
}

/// Turns a phone model into something that can be part of a file name
/// (`XT2451-2` stays as it is, anything else becomes `_`).
pub(crate) fn sanitize(name: &str) -> String {
    name.chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || matches!(character, '-' | '_' | '.') {
                character
            } else {
                '_'
            }
        })
        .collect::<String>()
        .trim_matches('_')
        .to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn package() -> FlashPackage {
        FlashPackage {
            directory: PathBuf::from("/firmware/arcfox"),
            flashfile: PathBuf::from("/firmware/arcfox/flashfile.xml"),
            model: Some("XT2451-2".to_owned()),
            software_version: Some("U1SJS34.72-35-3".to_owned()),
            cid: Some("0x0032".to_owned()),
            project_code: Some("arcfox_50".to_owned()),
            ignored_partitions: Vec::new(),
            steps: vec![
                FlashOp::Flash {
                    partition: "boot".to_owned(),
                    file: "boot.img".to_owned(),
                    md5: Some("abc".to_owned()),
                },
                FlashOp::Oem {
                    var: "config bootmode fastboot".to_owned(),
                },
                FlashOp::Getvar {
                    var: "max-sparse-size".to_owned(),
                },
                FlashOp::Erase {
                    partition: "userdata".to_owned(),
                },
            ],
        }
    }

    fn job<'a>(
        package: &'a FlashPackage,
        steps: &'a [FlashOp],
        extra_erases: &'a [String],
        engine: &'a Engine,
        serial: &'a str,
        shell: Shell,
    ) -> ScriptJob<'a> {
        ScriptJob {
            package,
            steps,
            extra_erases,
            engine,
            copied_tool: None,
            serial,
            shell,
        }
    }

    #[test]
    fn cmd_script_runs_the_selected_steps() {
        let package = package();
        let steps = vec![
            FlashOp::Flash {
                partition: "boot".to_owned(),
                file: "boot.img".to_owned(),
                md5: None,
            },
            FlashOp::Oem {
                var: "fb_mode_clear".to_owned(),
            },
        ];
        let extra = vec!["modemst1".to_owned(), "modemst2".to_owned()];
        let engine = Engine::Builtin;

        let script = render(&job(
            &package,
            &steps,
            &extra,
            &engine,
            "ZY22ABC",
            Shell::Cmd,
        ));

        assert!(script.starts_with("@echo off\n"));
        assert!(script.contains("cd /d \"/firmware/arcfox\"\n"));
        assert!(script.contains("set \"FASTBOOT=fastboot\"\n"));
        assert!(script.contains("set \"SERIAL=ZY22ABC\"\n"));
        assert!(script.contains("\"%FASTBOOT%\" -s \"%SERIAL%\" flash boot \"boot.img\"\n"));
        assert!(script.contains("\"%FASTBOOT%\" -s \"%SERIAL%\" oem fb_mode_clear\n"));
        assert!(script.contains("\"%FASTBOOT%\" -s \"%SERIAL%\" erase modemst2\n"));
        // Only the selected procedures, and no leftover of the others.
        assert!(!script.contains("getvar"));
    }

    #[test]
    fn sh_script_quotes_every_value() {
        let package = package();
        let steps = vec![FlashOp::Flash {
            partition: "boot".to_owned(),
            file: "boot image.img".to_owned(),
            md5: None,
        }];
        let engine = Engine::Mfastboot(crate::flash_engine::Mfastboot {
            version: "34.0.4".to_owned(),
            path: PathBuf::from("/opt/mfastboot 34/mfastboot"),
            emulator: crate::flash_engine::Emulator::Native,
            origin: crate::flash_engine::Origin::Shipped,
        });

        let script = render(&job(&package, &steps, &[], &engine, "", Shell::Sh));

        assert!(script.starts_with("#!/bin/sh\n"));
        assert!(script.contains("FASTBOOT=\"/opt/mfastboot 34/mfastboot\"\n"));
        assert!(script.contains("\"$FASTBOOT\" flash boot \"boot image.img\"\n"));
        // No device selected: no `SERIAL` line and no `-s`.
        assert!(!script.contains("SERIAL="));
        assert!(!script.contains(" -s "));
    }

    /// A directory of its own for a test, removed first so leftovers from an
    /// interrupted run cannot pass for a result.
    fn test_dir(name: &str) -> PathBuf {
        let directory = std::env::temp_dir().join(format!("lmnflash-flash-script-{name}"));
        let _ = std::fs::remove_dir_all(&directory);
        std::fs::create_dir_all(&directory).unwrap();

        directory
    }

    /// A shipped `mfastboot` build at `path`.
    fn tool(path: &str) -> Engine {
        Engine::Mfastboot(crate::flash_engine::Mfastboot {
            version: "34.0.4".to_owned(),
            path: PathBuf::from(path),
            emulator: crate::flash_engine::Emulator::Native,
            origin: crate::flash_engine::Origin::Shipped,
        })
    }

    #[test]
    fn a_copied_tool_is_started_from_the_scripts_own_folder() {
        let package = package();
        let steps = vec![FlashOp::Flash {
            partition: "boot".to_owned(),
            file: "boot.img".to_owned(),
            md5: None,
        }];
        let engine = tool("/opt/mfastboot/mfastboot.exe");

        for (shell, assignment, command) in [
            (
                Shell::Cmd,
                "set \"FASTBOOT=%~dp0mfastboot.exe\"\n",
                "\"%FASTBOOT%\" flash boot \"boot.img\"\n",
            ),
            (
                Shell::Sh,
                "FASTBOOT=\"$(cd \"$(dirname \"$0\")\" && pwd)/mfastboot.exe\"\n",
                "\"$FASTBOOT\" flash boot \"boot.img\"\n",
            ),
        ] {
            let mut job = job(&package, &steps, &[], &engine, "", shell);
            job.copied_tool = Some("mfastboot.exe");

            let script = render(&job);

            assert!(script.contains(assignment), "{shell:?}: {script}");
            assert!(script.contains(command), "{shell:?}: {script}");
            // The tool where it is installed is not named any more.
            assert!(!script.contains("/opt/mfastboot"), "{shell:?}: {script}");
        }
    }

    #[test]
    fn the_tool_is_copied_with_the_helpers_it_loads_on_windows() {
        let source = test_dir("tool");
        let target = test_dir("target");

        for name in ["mfastboot.exe", "AdbWinApi.dll", "AdbWinUsbApi.dll"] {
            std::fs::write(source.join(name), name).unwrap();
        }

        let tool = crate::flash_engine::Mfastboot {
            version: "34.0.4".to_owned(),
            path: source.join("mfastboot.exe"),
            emulator: crate::flash_engine::Emulator::Native,
            origin: crate::flash_engine::Origin::Shipped,
        };

        // A Windows build loads the two DLLs from its own folder, so they are
        // written beside the tool.
        assert_eq!(copy_tool_into(&tool, &target, true).unwrap(), "mfastboot.exe");
        assert!(target.join("mfastboot.exe").is_file());
        assert!(target.join("AdbWinApi.dll").is_file());
        assert!(target.join("AdbWinUsbApi.dll").is_file());

        // Everywhere else only the tool itself is written.
        let plain = test_dir("plain");
        assert_eq!(
            copy_tool_into(&tool, &plain, false).unwrap(),
            "mfastboot.exe"
        );
        assert!(plain.join("mfastboot.exe").is_file());
        assert!(!plain.join("AdbWinApi.dll").exists());
    }

    #[test]
    fn a_copy_gets_a_name_a_script_can_write() {
        let source = test_dir("spaced");
        let target = test_dir("spaced-copy");
        std::fs::write(source.join("mfastboot 34.exe"), "binary").unwrap();

        let tool = crate::flash_engine::Mfastboot {
            version: "34.0.4".to_owned(),
            path: source.join("mfastboot 34.exe"),
            emulator: crate::flash_engine::Emulator::Native,
            origin: crate::flash_engine::Origin::Shipped,
        };

        let name = copy_tool_into(&tool, &target, false).unwrap();

        // A space would split the command in both shells.
        assert_eq!(name, "mfastboot_34.exe");
        assert!(target.join("mfastboot_34.exe").is_file());
    }

    #[test]
    fn a_script_in_the_tools_own_folder_leaves_the_tool_alone() {
        let folder = test_dir("same-folder");
        std::fs::write(folder.join("mfastboot.exe"), "binary").unwrap();

        let tool = crate::flash_engine::Mfastboot {
            version: "34.0.4".to_owned(),
            path: folder.join("mfastboot.exe"),
            emulator: crate::flash_engine::Emulator::Native,
            origin: crate::flash_engine::Origin::Shipped,
        };

        // The folder of the script can be the folder of the tool; copying a
        // file onto itself would empty it.
        assert_eq!(
            copy_tool_into(&tool, &folder, false).unwrap(),
            "mfastboot.exe"
        );
        assert_eq!(
            std::fs::read_to_string(folder.join("mfastboot.exe")).unwrap(),
            "binary"
        );
    }

    #[test]
    fn file_names_follow_the_model_and_shell() {
        assert_eq!(Shell::Cmd.file_name(Some("XT2451-2")), "XT2451-2_flash.cmd");
        assert_eq!(Shell::Sh.file_name(Some("XT2451-2")), "XT2451-2_flash.sh");
        assert_eq!(Shell::Cmd.file_name(Some(" XT 2451 ")), "XT_2451_flash.cmd");
        assert_eq!(Shell::Cmd.file_name(None), "flash.cmd");
        assert_eq!(Shell::Sh.file_name(Some("")), "flash.sh");
    }

    #[test]
    fn the_host_decides_the_shell() {
        let expected = if cfg!(windows) { Shell::Cmd } else { Shell::Sh };

        assert_eq!(Shell::for_host(), expected);
    }
}
